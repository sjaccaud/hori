#!/usr/bin/env bash
# Create the `cli-admin` break-glass account and harden the sudoers state.
#
# This script does NOT remove the primary <user> from the `sudo` or `docker`
# groups; it only removes clearly unused groups and consolidates the existing
# safe NOPASSWD rules. The goal is a clean break-glass + sudoers baseline,
# not a full lock-out.
#
# Usage: sudo ./scripts/hardening/install_cli_admin.sh
set -euo pipefail

shopt -s nullglob

if [ "$(id -u)" -ne 0 ]; then
    echo "ERROR: This script must be run as root (sudo)."
    echo "  sudo $0"
    exit 1
fi

# Detect the human user who invoked sudo. This is the account that will keep
# day-to-day sudo access; cli-admin is the break-glass.
PRIMARY_USER="${SUDO_USER:-$(logname 2>/dev/null || echo "")}"
if [ -z "$PRIMARY_USER" ] || [ "$PRIMARY_USER" = "root" ]; then
    echo "ERROR: Could not detect the primary user. Run with sudo from the user account."
    exit 1
fi

# Groups that are root-equivalent (lxd) or almost certainly unused on this rig.
# Removing them reduces attack surface without affecting Devin CLI / day-to-day work.
REMOVE_GROUPS=(lxd ollama lpadmin cdrom dip plugdev)

# Old, stale, or redundant sudoers fragments that should no longer exist.
# The two .bak.* files are ignored by sudo because their names contain '.',
# but they are clutter and one contains a dangerously broad old NOPASSWD rule.
STALE_SUDOERS=(
    /etc/sudoers.d/10-devin
    /etc/sudoers.d/10-devin.bak
    /etc/sudoers.d/10-devin.bak.*
    /etc/sudoers.d/aios-admin
    /etc/sudoers.d/aios-admin.bak
    /etc/sudoers.d/aios-admin.bak.*
    /etc/sudoers.d/hori-admin
    /etc/sudoers.d/hori-admin.bak
    /etc/sudoers.d/hori-admin.bak.*
    "/etc/sudoers.d/${PRIMARY_USER}-shutdown"
    /etc/sudoers.d/nopasswd-suspend
    /etc/sudoers.d/pyxx
    /etc/sudoers.d/pyxx-fail2ban
)

HORI_USER_SUDOERS=/etc/sudoers.d/hori-user

echo "=== cli-admin break-glass + sudoers hygiene ==="
echo

# --- Create cli-admin break-glass account ---
if ! id -u cli-admin >/dev/null 2>&1; then
    echo "Creating cli-admin break-glass account..."
    useradd -m -s /bin/bash -G sudo cli-admin
    echo
    echo "Set a strong password for cli-admin and record it offline:"
    passwd cli-admin
else
    echo "cli-admin already exists; ensuring it is in the sudo group."
    usermod -aG sudo cli-admin 2>/dev/null || true
fi

# --- Remove primary user from clearly unused groups ---
echo
echo "Removing $PRIMARY_USER from low-risk / unused groups..."
for group in "${REMOVE_GROUPS[@]}"; do
    if getent group "$group" >/dev/null && id -nG "$PRIMARY_USER" | grep -qw "$group"; then
        gpasswd -d "$PRIMARY_USER" "$group"
        echo "  removed $PRIMARY_USER from $group"
    else
        echo "  $group: not a member or group does not exist (skipping)"
    fi
done

# --- Clean up stale sudoers files ---
echo
echo "Cleaning stale /etc/sudoers.d/ fragments..."
for f in "${STALE_SUDOERS[@]}"; do
    if [ -f "$f" ]; then
        echo "  removing $f"
        rm -f "$f"
    fi
done

# --- Consolidate the primary user's safe NOPASSWD rules ---
echo
echo "Installing $HORI_USER_SUDOERS with safe NOPASSWD rules for $PRIMARY_USER..."
cat > "$HORI_USER_SUDOERS" <<EOF
# HORI primary user — safe NOPASSWD commands.
#
# The primary account still has full password-protected sudo via the %sudo
# rule in /etc/sudoers. This file only allows a small number of safe,
# frequently automated commands to run without a password.
#
# Generated by: scripts/hardening/install_cli_admin.sh
# Do not edit directly; re-run the installer.

$PRIMARY_USER ALL=(ALL) NOPASSWD: /usr/sbin/shutdown, /usr/sbin/poweroff, /usr/bin/systemctl suspend, /usr/sbin/ufw status, /usr/bin/fail2ban-client status, /usr/bin/fail2ban-client status sshd
EOF
chmod 0440 "$HORI_USER_SUDOERS"

# --- Validate ---
echo
visudo -c

echo
echo "Done. Summary:"
echo "  - cli-admin break-glass account created/verified."
echo "  - $PRIMARY_USER removed from: ${REMOVE_GROUPS[*]}"
echo "  - stale sudoers fragments removed."
echo "  - safe NOPASSWD rules consolidated into $HORI_USER_SUDOERS."
echo
echo "Next steps:"
echo "  1. Record the cli-admin password offline."
echo "  2. Verify with: sudo ./scripts/hardening/test_cli_admin.sh"
echo "  3. Run 'make test' to confirm nothing broke."
