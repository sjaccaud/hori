import Foundation
import WebKit

/// Injects HTML components into the live canvas without full page reloads.
///
/// Instead of asking HORI to regenerate the full page every turn (which
/// causes truncation, lost functionality, and context bloat), the Mac app
/// asks HORI to generate just the new component — an HTML fragment plus
/// any JavaScript needed. The ComponentInjector inserts it into the
/// existing WKWebView's DOM.
///
/// This is the architectural fix for iterative building:
/// - HORI generates ~200 tokens (a button + handler), not ~5000 (full page)
/// - The existing page is preserved exactly — nothing gets dropped
/// - Context window stays clean — no canvas_html needed for modifications
/// - Works on any model size, even 8B
///
/// Traces to: Component Injection slice — iterative building without bloat.
struct ComponentInjector {

    /// A component generated by HORI for injection into the canvas.
    /// Contains an HTML fragment and optional JavaScript to wire it up.
    struct Component: Equatable {
        var html: String          // HTML fragment to insert
        var javascript: String?   // JS to run after insertion (event handlers, etc.)
        var insertTarget: String? // CSS selector for where to insert (default: body)
        var insertPosition: InsertPosition // where relative to target
    }

    /// Where to insert the component relative to the target element.
    enum InsertPosition: String, Equatable {
        case appendChild   // inside target, at the end
        case prependChild  // inside target, at the beginning
        case before         // before target
        case after          // after target
        case replace        // replace target entirely
    }

    // MARK: - Extraction

    /// Extracts a component from HORI's reply text.
    /// HORI generates components in fenced blocks:
    ///   ```component
    ///   target: #picker-container
    ///   position: after
    ///   <button id="save">Save Color</button>
    ///   <script>
    ///   document.getElementById("save").addEventListener("click", ...)
    ///   </script>
    ///   ```
    /// - Parameter text: HORI's reply text.
    /// - Returns: The extracted component, or nil if no component block found.
    static func extractComponent(from text: String) -> Component? {
        // Match ```component ... ``` blocks
        let pattern = #"(?s)```[cC]omponent\s*\n(.*?)(?:```|$)"#
        guard let regex = try? NSRegularExpression(pattern: pattern, options: []) else {
            return nil
        }

        let range = NSRange(text.startIndex..., in: text)
        guard let match = regex.firstMatch(in: text, range: range),
              match.numberOfRanges > 1,
              let contentRange = Range(match.range(at: 1), in: text) else {
            return nil
        }

        let raw = String(text[contentRange]).trimmingCharacters(in: .whitespacesAndNewlines)
        return parseComponent(raw)
    }

    /// Parses the raw component block content into a Component.
    private static func parseComponent(_ raw: String) -> Component? {
        var target: String?
        var position: InsertPosition = .appendChild
        var htmlParts: [String] = []
        var jsParts: [String] = []

        // Split into lines and parse header directives vs HTML/JS
        let lines = raw.components(separatedBy: "\n")
        var inScript = false
        var inHTML = false

        for line in lines {
            let trimmed = line.trimmingCharacters(in: .whitespaces)

            if inScript {
                if trimmed == "</script>" {
                    inScript = false
                } else {
                    jsParts.append(line)
                }
                continue
            }

            if trimmed.hasPrefix("<script") {
                inScript = true
                continue
            }

            // Parse header directives (target:, position:)
            if trimmed.lowercased().hasPrefix("target:") {
                target = trimmed.split(separator: ":")[1].trimmingCharacters(in: .whitespaces)
                continue
            }

            if trimmed.lowercased().hasPrefix("position:") {
                let posStr = trimmed.split(separator: ":")[1].trimmingCharacters(in: .whitespaces).lowercased()
                position = InsertPosition(rawValue: posStr) ?? .appendChild
                continue
            }

            // Everything else is HTML
            if !trimmed.isEmpty {
                inHTML = true
                htmlParts.append(line)
            }
        }

        let html = htmlParts.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
        guard !html.isEmpty else { return nil }

        let js = jsParts.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
        return Component(
            html: html,
            javascript: js.isEmpty ? nil : js,
            insertTarget: target,
            insertPosition: position
        )
    }

    // MARK: - Injection

    /// Injects a component into the WKWebView's DOM.
    /// - Parameters:
    ///   - component: The component to inject.
    ///   - webView: The live WKWebView showing the canvas.
    ///   - completion: Called with true on success, false on failure.
    static func inject(_ component: Component, into webView: WKWebView,
                       completion: @escaping (Bool) -> Void) {
        let target = component.insertTarget ?? "body"
        let position = component.insertPosition.rawValue

        // Escape the HTML for JavaScript string
        let escapedHTML = component.html
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "'", with: "\\'")
            .replacingOccurrences(of: "\n", with: "\\n")
            .replacingOccurrences(of: "\r", with: "")

        // Build the injection script
        var script = """
        (function() {
            var target = document.querySelector('\(target)');
            if (!target) { return false; }
            var container = document.createElement('div');
            container.innerHTML = '\(escapedHTML)';
            var fragment = document.createDocumentFragment();
            while (container.firstChild) {
                fragment.appendChild(container.firstChild);
            }
        """

        switch component.insertPosition {
        case .appendChild:
            script += "target.appendChild(fragment);\n"
        case .prependChild:
            script += "target.insertBefore(fragment, target.firstChild);\n"
        case .before:
            script += "target.parentNode.insertBefore(fragment, target);\n"
        case .after:
            script += "target.parentNode.insertBefore(fragment, target.nextSibling);\n"
        case .replace:
            script += "target.parentNode.replaceChild(fragment, target);\n"
        }

        script += "return true;\n})();"

        // Execute the injection
        webView.evaluateJavaScript(script) { result, error in
            if let error = error {
                print("ComponentInjector error: \(error.localizedDescription)")
                completion(false)
                return
            }

            // Run the component's JavaScript (if any) after insertion
            if let js = component.javascript, !js.isEmpty {
                webView.evaluateJavaScript(js) { _, jsError in
                    if let jsError = jsError {
                        print("ComponentInjector JS error: \(jsError.localizedDescription)")
                    }
                    completion(jsError == nil)
                }
            } else {
                completion(true)
            }
        }
    }

    // MARK: - DOM Inspection

    /// Gets a summary of the current DOM structure for context.
    /// This is sent to HORI so she knows what's on the page without
    /// needing the full HTML — just the element structure.
    /// - Parameter webView: The live WKWebView.
    /// - Returns: A compact DOM summary like "body > div.container > h1, input#picker, p#val"
    static func getDOMSummary(from webView: WKWebView,
                              completion: @escaping (String?) -> Void) {
        let script = """
        (function() {
            function summarize(el, depth) {
                if (depth > 3) return '...';
                var tag = el.tagName.toLowerCase();
                var id = el.id ? '#' + el.id : '';
                var cls = el.className && typeof el.className === 'string'
                    ? '.' + el.className.split(' ').filter(Boolean).join('.') : '';
                var label = tag + id + cls;
                var children = [];
                for (var i = 0; i < el.children.length && i < 10; i++) {
                    children.push(summarize(el.children[i], depth + 1));
                }
                if (children.length) {
                    return label + ' > [' + children.join(', ') + ']';
                }
                return label;
            }
            return summarize(document.body, 0);
        })();
        """

        webView.evaluateJavaScript(script) { result, error in
            if let error = error {
                print("DOMSummary error: \(error.localizedDescription)")
                completion(nil)
                return
            }
            completion(result as? String)
        }
    }
}
